#!/bin/bash
# ============================================================
# QuantMonitorV6 云端推送调度（魔搭服务器版 · 北京时间）
# 由 crontab 每 10 分钟调用一次；按当前时刻判定槽位后执行推送。
# 说明：与原 GitHub Actions 的 case 判定等价（原表用 UTC，本表直接写北京时间）。
# ============================================================
cd "$(dirname "$0")/tools"

# 密钥（如已在 env.sh 中 export 则此处无需重复；两处都放以保稳妥）
if [ -f env.sh ]; then
  . ./env.sh
fi

H=$(date +%H); M=$(date +%M)
case $H:$M in
  08:2[0-4])   T=warn ;;      # 板块启动预警
  08:3[0-4])   T=pre ;;       # 盘前速递
  09:2[0-9])   T=auction ;;   # 竞价观察
  12:0[0-4]|14:0[1-4]|16:0[0-4]) T=news2h ;;  # 两小时市场消息汇总
  10:0[0-4]|11:0[0-4]|13:0[0-4]|14:0[0-4]) T=hourly ;;  # 盘中解读
  11:4[0-4])   T=news ;;      # 午间事件简报
  14:0[5-7])   T=follow ;;    # 跟涨三步走·盘中档
  15:0[5-8])   T=follow ;;    # 跟涨三步走·收盘档
  15:2[0-3])   T=anchor ;;    # 突破回踩·主力成本锚
  15:3[0-4])   T=review ;;    # 突破回踩·复盘
  20:0[0-2])   T=evaluate ;;  # 周日策略评估
  15:1[0-4])   T=news ;;      # 尾盘事件简报
  15:3[5-9])   T=news ;;
  21:3[6-9]|22:3[6-9]) T=ext ;;  # 外盘窗口
  22:5[0-9])   T=evening ;;   # 晚间消息汇总
  11:3[0-5])   T=noon ;;      # 午间作战
  15:*)        T=eod ;;       # 收盘复盘
  *)           T=watch ;;     # 盘中异动兜底（非窗口静默）
esac

echo "$(date '+%F %T') slot=$T H=$H M=$M" >> ../logs/sched.log
python3 cloud_daily_review.py --time "$T" >> ../logs/push_$(date +%Y%m%d).log 2>&1
