_cache = {}


def lines_of(rel, bak=None):
    """读某个文件（或它的备份）的全部行。"""
    key = (rel, bak)
    if key in _cache:
        return _cache[key]
    p = ROOT + rel + (("." + bak) if bak else "")
    if not os.path.exists(p):
        _cache[key] = None
        return None
    raw = open(p, "rb").read()
    _cache[key] = raw.decode("utf-8-sig").splitlines()
    return _cache[key]


def find(rel, pat, bak=None, ctx=0):
    """按正则定位，返回 [(行号, [行...]), ...]。"""
    ls = lines_of(rel, bak)
    if ls is None:
        return [("文件缺失：%s%s" % (rel, ("." + bak) if bak else ""), [])]
    out = []
    for i, ln in enumerate(ls, 1):
        if re.search(pat, ln):
            a = max(0, i - 1 - ctx)
            b = min(len(ls), i + ctx)
            out.append((i, ls[a:b]))
    return out


def meta(rel):
    p = ROOT + rel
    raw = open(p, "rb").read()
    crlf = raw.count(b"\r\n")
    lf = raw.count(b"\n") - crlf
    eol = "CRLF" if crlf and not lf else ("LF" if lf and not crlf else "MIXED")
    return len(raw.decode("utf-8-sig").splitlines()), eol


def region(rel, start, end, title, bak=None, lang="python"):
    """输出一个显式行号区间（用于常量块这类整段展示）。"""
    key = (rel, bak)
    seen = _seen.setdefault(key, set())
    ls = lines_of(rel, bak)
    if ls is None:
        W("**%s**" % title)
        W("")
        W("```text")
        W("文件缺失：%s%s" % (rel, ("." + bak) if bak else ""))
        W("```")
        W("")
        return
    W("**%s**%s" % (title, ("（备份 %s.%s）" % (rel, bak)) if bak else ""))
    W("")
    W("```%s" % lang)
    for n in range(start, min(end, len(ls)) + 1):
        seen.add(n)
        W("L%-5d %s" % (n, ls[n - 1].rstrip()))
    W("```")
    W("")


