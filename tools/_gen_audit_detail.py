_seen = {}          # rel -> set(已输出过的行号)，同一行只输出一次，避免松散锚点刷重复片段


def block(rel, pat, title, bak=None, ctx=0, lang="python"):
    """输出一处定位结果。同一文件的同一行只输出一次。"""
    tag = "（备份 %s.%s）" % (rel, bak) if bak else ""
    key = (rel, bak)
    seen = _seen.setdefault(key, set())
    emitted = False
    buf = []
    for lineno, ls in find(rel, pat, bak=bak, ctx=ctx):
        if isinstance(lineno, str):
            buf.append(("```text\n%s\n```\n" % lineno))
            continue
        if lineno in seen:          # 该锚点行已输出过 → 整块跳过
            continue
        txt = ["```%s" % lang]
        base = lineno - ctx
        for k, t in enumerate(ls):
            n = base + k
            seen.add(n)
            txt.append("L%-5d %s%s" % (n, t.rstrip(), "  <<<" if n == lineno else ""))
        txt.append("```")
        buf.append("\n".join(txt) + "\n")
        emitted = True
    if not buf:
        return
    W("**%s**%s" % (title, tag))
    W("")
    for b in buf:
        W(b)
    _ = emitted



