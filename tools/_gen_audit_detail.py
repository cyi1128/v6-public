def dump(rel, pat, bak=None, ctx=3, note=""):
    """把某个文件里匹配到的行连同上下文按代码块打印出来（行号来自磁盘实读）。"""
    ls = lines_of(rel, bak)
    if ls is None:
        W("> 文件缺失：`%s%s`" % (rel, ("." + bak) if bak else ""))
        return
    hits = [i for i, ln in enumerate(ls, 1) if re.search(pat, ln)]
    W("`%s`%s 命中 %d 处 %s" % (rel, ("." + bak) if bak else "", len(hits), note))
    W("")
    W("```python")
    for i in hits:
        a = max(0, i - 1 - ctx)
        b = min(len(ls), i + ctx)
        for j in range(a, b):
            mark = ">>" if (j + 1) == i else "  "
            W("%s L%-5d %s" % (mark, j + 1, ls[j]))
        if len(hits) > 1:
            W("   " + "-" * 60)
    W("```")
    W("")


