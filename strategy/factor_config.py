# ============================================================
# 工具函数
# ============================================================
def get_score_by_range(value, score_config):
    """根据数值区间获取评分和标签"""
    for min_val, max_val, score, label in score_config:
        if min_val <= value < max_val:
            return score, label
    # 超出范围返回最后一个
    if score_config:
        return score_config[-1][2], score_config[-1][3]
    return 50, '未知'


def get_score_level(total_score):
    """根据总分获取等级"""
    for min_s, max_s, level, desc in SCORE_LEVELS:
        if min_s <= total_score < max_s:
            return level, desc
    return '未知', ''


def get_position_by_score(total_score):
    """根据总分获取基础仓位"""
    for min_s, max_s, pos, label in POSITION_BY_SCORE:
        if min_s <= total_score < max_s:
            return pos, label
    return 0.0, '观望'
